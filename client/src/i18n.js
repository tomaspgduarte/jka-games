const fill = (text, vars) => text.replace(/\{(\w+)\}/g, (match, key) => key in vars ? vars[key] : match);

export function translate(lang, text, vars = {}) {
  if (lang !== 'en') return fill(text, vars);
  // Server validation errors arrive as «Pergunta N: detalhe».
  const question = /^Pergunta (\d+): (.+)$/.exec(text);
  const english = en[text] ?? (question ? `Question ${question[1]}: ${en[question[2]] ?? question[2]}` : text);
  return fill(english, vars);
}

export const LangContext = createContext({ lang: 'pt', setLang() {} });
export function useT() {
  const { lang } = useContext(LangContext);
  return (text, vars) => translate(lang, text, vars);
}
// Messages are kept as Portuguese keys (or { text, vars }) and translated when shown.
export function useMessage() {
  const t = useT();
  return message => typeof message === 'string' ? t(message) : t(message.text, message.vars);
}
